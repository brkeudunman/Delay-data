"""
target_breakdown.py — class balance of ARR_DELAY per split (read-only diagnostic)
=========================================================================
Loads Flight_tab_2020.csv exactly as the ablation runner does (common/base_config.yaml
-> common.data.load_splits: dropna, FL_DAY split) and reports, per split and in total:

  early   = ARR_DELAY < -thr
  on time = |ARR_DELAY| <= thr
  late    = ARR_DELAY > thr

plus the `abs` positive rate (|ARR_DELAY| > thr), the `late` positive rate (ARR_DELAY > thr)
and the share of `abs` positives that are early arrivals. thr = run.delay_threshold (15).

Writes aggregate/target_breakdown.md and prints it. No training.

    uv run python exp/Tab_exp/ablations/aggregate/target_breakdown.py
"""
import sys
from pathlib import Path

import pandas as pd
import yaml

HERE = Path(__file__).resolve().parent
ABLATIONS = HERE.parent
sys.path.insert(0, str(ABLATIONS))
from common import data as D  # noqa: E402


def breakdown(arr: pd.Series, thr: float) -> dict:
    n = len(arr)
    early = int((arr < -thr).sum())
    late = int((arr > thr).sum())
    on_time = int((arr.abs() <= thr).sum())
    assert early + late + on_time == n
    abs_pos = early + late
    return {
        "rows": n,
        "early": early, "on_time": on_time, "late": late,
        "early_share": early / n, "on_time_share": on_time / n, "late_share": late / n,
        "abs_pos_rate": abs_pos / n,
        "late_pos_rate": late / n,
        "early_share_of_abs_pos": early / abs_pos if abs_pos else float("nan"),
    }


def main():
    cfg = yaml.safe_load((ABLATIONS / "common" / "base_config.yaml").read_text(encoding="utf-8"))
    thr = float(cfg["run"]["delay_threshold"])
    d = cfg["data"]
    df_train, df_val, df_test, *_ = D.load_splits(cfg)

    splits = {
        f"train (FL_DAY ≤ {d['train_days_max']})": df_train,
        f"val ({d['train_days_max'] + 1}–{d['val_days_max']})": df_val,
        f"test (> {d['val_days_max']})": df_test,
    }
    rows = {name: breakdown(df["ARR_DELAY"], thr) for name, df in splits.items()}
    rows["total"] = breakdown(pd.concat([df["ARR_DELAY"] for df in splits.values()]), thr)

    pct = lambda x: f"{100 * x:.2f}%"  # noqa: E731
    t = int(thr)
    lines = [
        "# Target breakdown",
        "",
        f"`{d['file']}` after `dropna`, split by `FL_DAY` as in `common/data.load_splits` "
        f"(threshold = {thr:g} min). Generated by `aggregate/target_breakdown.py`.",
        "",
        "## Counts",
        "",
        f"| split | rows | early (< −{t}) | on time (\\|·\\| ≤ {t}) | late (> {t}) |",
        "|---|---:|---:|---:|---:|",
    ]
    for name, r in rows.items():
        lines.append(f"| {name} | {r['rows']:,} | {r['early']:,} ({pct(r['early_share'])}) | "
                     f"{r['on_time']:,} ({pct(r['on_time_share'])}) | {r['late']:,} ({pct(r['late_share'])}) |")
    lines += [
        "",
        "## Binary targets",
        "",
        f"| split | `abs` positive rate (\\|ARR_DELAY\\| > {t}) | `late` positive rate (> {t}) "
        f"| early share of `abs` positives |",
        "|---|---:|---:|---:|",
    ]
    for name, r in rows.items():
        lines.append(f"| {name} | {pct(r['abs_pos_rate'])} | {pct(r['late_pos_rate'])} | "
                     f"{pct(r['early_share_of_abs_pos'])} |")
    md = "\n".join(lines) + "\n"

    out = HERE / "target_breakdown.md"
    out.write_text(md, encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print(md)
    print(f"-> {out}")


if __name__ == "__main__":
    main()
